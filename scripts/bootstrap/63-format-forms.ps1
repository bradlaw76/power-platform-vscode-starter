function Get-FormFormatterProperty {
    param($Object, [string]$Name, $Default = $null)
    if ($null -eq $Object) { return $Default }
    $property = $Object.PSObject.Properties[$Name]
    if ($null -eq $property) { return $Default }
    return $property.Value
}

function ConvertTo-FormFormatterStableGuid {
    param([Parameter(Mandatory)] [string]$Value)
    $bytes = [Security.Cryptography.SHA256]::HashData([Text.Encoding]::UTF8.GetBytes($Value))
    $guidBytes = [byte[]]$bytes[0..15]
    $guidBytes[7] = [byte](($guidBytes[7] -band 0x0f) -bor 0x50)
    $guidBytes[8] = [byte](($guidBytes[8] -band 0x3f) -bor 0x80)
    return ([guid]::new($guidBytes)).ToString()
}

function Get-FormFormatterHash {
    param([Parameter(Mandatory)] [string]$Value)
    $bytes = [Security.Cryptography.SHA256]::HashData([Text.Encoding]::UTF8.GetBytes($Value))
    return ([Convert]::ToHexString($bytes)).ToLowerInvariant()
}

function ConvertTo-FormFormatterHtml {
    param([AllowEmptyString()] [string]$Value)
    return [Net.WebUtility]::HtmlEncode($Value ?? '')
}

function Get-FormFormatterBoolean {
    param($Value, [bool]$Default)
    if ($null -eq $Value) { return $Default }
    return [bool]$Value
}

function Get-FormFormatterOwnedName {
    param(
        [string]$ScenarioSlug,
        [string]$TableLogicalName,
        [ValidateSet('tab', 'section')] [string]$Kind,
        [string]$Key
    )
    return "$script:FormatterPrefix-$ScenarioSlug-$TableLogicalName-$Kind-$Key"
}

function Assert-FormFormatterXml {
    param([Parameter(Mandatory)] [string]$FormXml, [string]$FormName)
    try {
        [xml]$document = $FormXml
        if ($null -eq $document.DocumentElement -or $document.DocumentElement.Name -cne 'form') {
            throw 'The root element must be <form>.'
        }
        return $document
    } catch {
        throw "Invalid FormXml for '$FormName': $($_.Exception.Message)"
    }
}

function New-FormFormatterElement {
    param(
        [xml]$Document,
        [string]$Name,
        [hashtable]$Attributes = @{}
    )
    $node = $Document.CreateElement($Name)
    foreach ($key in @($Attributes.Keys | Sort-Object)) {
        $node.SetAttribute($key, "$($Attributes[$key])")
    }
    return $node
}

function Add-FormFormatterLabel {
    param([xml]$Document, [Xml.XmlElement]$Parent, [string]$Text)
    $labels = New-FormFormatterElement -Document $Document -Name 'labels'
    [void]$labels.AppendChild((New-FormFormatterElement -Document $Document -Name 'label' -Attributes @{
        description = $Text
        languagecode = '1033'
    }))
    [void]$Parent.AppendChild($labels)
}

function Get-FormFormatterFieldSpec {
    param($Field)
    if ($Field -is [string]) {
        return [pscustomobject][ordered]@{ logicalName = $Field; label = ''; component = '' }
    }
    return [pscustomobject][ordered]@{
        logicalName = "$(Get-FormFormatterProperty $Field 'logicalName' '')"
        label = "$(Get-FormFormatterProperty $Field 'label' '')"
        component = "$(Get-FormFormatterProperty $Field 'component' '')"
    }
}

function Get-FormFormatterAttributeType {
    param($Attribute)
    $attributeType = "$(Get-FormFormatterProperty $Attribute 'AttributeType' '')"
    if (-not [string]::IsNullOrWhiteSpace($attributeType)) { return $attributeType }
    return "$(Get-FormFormatterProperty (Get-FormFormatterProperty $Attribute 'AttributeTypeName') 'Value' '')"
}

function Get-FormFormatterAttributeLabel {
    param($Attribute)
    $displayName = Get-FormFormatterProperty $Attribute 'DisplayName'
    $labels = @(Get-FormFormatterProperty $displayName 'LocalizedLabels' @())
    $english = @($labels | Where-Object { "$(Get-FormFormatterProperty $_ 'LanguageCode')" -eq '1033' } | Select-Object -First 1)
    if ($english.Count -eq 1 -and -not [string]::IsNullOrWhiteSpace("$(Get-FormFormatterProperty $english[0] 'Label')")) {
        return "$(Get-FormFormatterProperty $english[0] 'Label')"
    }
    $userLabel = Get-FormFormatterProperty (Get-FormFormatterProperty $displayName 'UserLocalizedLabel') 'Label'
    if (-not [string]::IsNullOrWhiteSpace("$userLabel")) { return "$userLabel" }
    return "$(Get-FormFormatterProperty $Attribute 'LogicalName')"
}

function Assert-FormFormatterContract {
    param($Payload)
    if ("$(Get-FormFormatterProperty $Payload 'version')" -cne '1.0') {
        throw "Unsupported form-layouts.json version. Expected '1.0'."
    }
    $forms = @(Get-FormFormatterProperty $Payload 'forms' @())
    if ($forms.Count -eq 0) { throw 'form-layouts.json must contain at least one form.' }

    $formKeys = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    foreach ($form in $forms) {
        $table = "$(Get-FormFormatterProperty $form 'tableLogicalName')"
        $name = "$(Get-FormFormatterProperty $form 'formName')"
        if (-not $formKeys.Add("$table|$name")) { throw "Duplicate form layout '$table|$name'." }
        if ("$(Get-FormFormatterProperty $form 'ownership')" -cne 'wizard-owned-only') {
            throw "Form '$name' must use ownership 'wizard-owned-only'."
        }
        $tabKeys = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
        $sectionKeys = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
        $fields = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
        foreach ($tab in @(Get-FormFormatterProperty $form 'tabs' @())) {
            $tabKey = "$(Get-FormFormatterProperty $tab 'key')"
            if (-not $tabKeys.Add($tabKey)) { throw "Duplicate tab key '$tabKey' in form '$name'." }
            foreach ($section in @(Get-FormFormatterProperty $tab 'sections' @())) {
                $sectionKey = "$(Get-FormFormatterProperty $section 'key')"
                if (-not $sectionKeys.Add($sectionKey)) { throw "Duplicate section key '$sectionKey' in form '$name'." }
                foreach ($fieldValue in @(Get-FormFormatterProperty $section 'fields' @())) {
                    $field = Get-FormFormatterFieldSpec $fieldValue
                    if (-not $fields.Add($field.logicalName)) {
                        throw "Duplicate field '$($field.logicalName)' in form '$name'."
                    }
                }
            }
        }
    }
}

function Get-FormFormatterFormMatch {
    param($Layout, [object[]]$Forms)
    $requestedId = "$(Get-FormFormatterProperty $Layout 'formId' '')".Trim('{}')
    if (-not [string]::IsNullOrWhiteSpace($requestedId)) {
        $matches = @($Forms | Where-Object { "$(Get-FormFormatterProperty $_ 'formid')".Trim('{}') -ieq $requestedId })
    } else {
        $matches = @($Forms | Where-Object { "$(Get-FormFormatterProperty $_ 'name')" -ceq "$(Get-FormFormatterProperty $Layout 'formName')" })
    }
    if ($matches.Count -eq 0) { throw "Main form '$($Layout.formName)' was not found for '$($Layout.tableLogicalName)'." }
    if ($matches.Count -gt 1) { throw "Ambiguous Main form '$($Layout.formName)' for '$($Layout.tableLogicalName)': found $($matches.Count)." }
    return $matches[0]
}

function Get-FormFormatterPlannedCells {
    param([xml]$Document, [Collections.Generic.HashSet[string]]$PlannedFields)

    $cells = @{}
    foreach ($control in @($Document.SelectNodes('/form/tabs//control[@datafieldname]'))) {
        if (-not $PlannedFields.Contains($control.GetAttribute('datafieldname'))) { continue }
        $logicalName = $control.GetAttribute('datafieldname').ToLowerInvariant()
        $cell = $control
        while ($null -ne $cell -and $cell.Name -cne 'cell') { $cell = $cell.ParentNode }
        if ($null -eq $cell) { throw "Field '$logicalName' is not contained by a form cell." }
        if ($cells.ContainsKey($logicalName)) { throw "Field '$logicalName' appears more than once on the source form." }
        $cells[$logicalName] = $cell.CloneNode($true)
    }

    foreach ($logicalName in $PlannedFields) {
        if (-not $cells.ContainsKey($logicalName)) {
            throw "Planned field '$logicalName' is not present on the baseline form. Run step 60 before formatting."
        }
    }
    return $cells
}

function Remove-FormFormatterPlannedCells {
    param([xml]$Document, [Collections.Generic.HashSet[string]]$PlannedFields)

    $affectedRows = [Collections.Generic.List[Xml.XmlElement]]::new()
    foreach ($control in @($Document.SelectNodes('/form/tabs//control[@datafieldname]'))) {
        if (-not $PlannedFields.Contains($control.GetAttribute('datafieldname'))) { continue }
        $cell = $control
        while ($null -ne $cell -and $cell.Name -cne 'cell') { $cell = $cell.ParentNode }
        if ($null -ne $cell -and $null -ne $cell.ParentNode) {
            $row = $cell.ParentNode
            while ($null -ne $row -and $row.Name -cne 'row') { $row = $row.ParentNode }
            if ($null -ne $row -and -not $affectedRows.Contains($row)) { $affectedRows.Add($row) }
            [void]$cell.ParentNode.RemoveChild($cell)
        }
    }
    foreach ($row in @($affectedRows.ToArray())) {
        if ($null -ne $row.ParentNode -and $row.SelectNodes('./cell').Count -eq 0) {
            [void]$row.ParentNode.RemoveChild($row)
        }
    }
}

function Set-FormFormatterFieldComponent {
            param(
                [xml]$Document,
                [Xml.XmlElement]$Cell,
                $Field,
                [string]$IdentityBase
            )
            if ([string]::IsNullOrWhiteSpace("$($Field.component)")) { return }

            $control = $Cell.SelectSingleNode('./control[@datafieldname]')
            if ($null -eq $control) { throw "Field '$($Field.logicalName)' does not contain a configurable form control." }
            $uniqueId = $control.GetAttribute('uniqueid')
            if ([string]::IsNullOrWhiteSpace($uniqueId)) {
                $uniqueId = "{$((ConvertTo-FormFormatterStableGuid "$IdentityBase|component"))}"
                $control.SetAttribute('uniqueid', $uniqueId)
            }

            $controlDescriptions = $Document.SelectSingleNode('/form/controlDescriptions')
            if ($null -eq $controlDescriptions) {
                $controlDescriptions = New-FormFormatterElement -Document $Document -Name 'controlDescriptions'
                [void]$Document.DocumentElement.AppendChild($controlDescriptions)
            }
            foreach ($existing in @($controlDescriptions.SelectNodes('./controlDescription'))) {
                if ($existing.GetAttribute('forControl') -ieq $uniqueId) {
                    [void]$controlDescriptions.RemoveChild($existing)
                }
            }

            $component = switch ($Field.component) {
                'toggle' {
                    [pscustomobject]@{
                        DefaultControlId = '{67FAC785-CD58-4F9F-ABB3-4B7DDC6ED5ED}'
                        Name = 'MscrmControls.FieldControls.ToggleControl'
                        ValueType = 'TwoOptions'
                    }
                }
                'option-set-wrapper' {
                    [pscustomobject]@{
                        DefaultControlId = '{3EF39988-22BB-4F0B-BBBE-64B5A3748AEE}'
                        Name = 'MscrmControls.OptionSet.OptionSetControl'
                        ValueType = 'OptionSet'
                    }
                }
                default { throw "Unsupported field component '$($Field.component)'." }
            }

            $description = New-FormFormatterElement -Document $Document -Name 'controlDescription' -Attributes @{ forControl = $uniqueId }
            $defaultControl = New-FormFormatterElement -Document $Document -Name 'customControl' -Attributes @{ id = $component.DefaultControlId }
            $defaultParameters = New-FormFormatterElement -Document $Document -Name 'parameters'
            $dataFieldName = New-FormFormatterElement -Document $Document -Name 'datafieldname'
            $dataFieldName.InnerText = $Field.logicalName
            [void]$defaultParameters.AppendChild($dataFieldName)
            [void]$defaultControl.AppendChild($defaultParameters)
            [void]$description.AppendChild($defaultControl)

            foreach ($formFactor in @(0, 1, 2)) {
                $customControl = New-FormFormatterElement -Document $Document -Name 'customControl' -Attributes @{
                    formFactor = "$formFactor"
                    name = $component.Name
                }
                $parameters = New-FormFormatterElement -Document $Document -Name 'parameters'
                $value = New-FormFormatterElement -Document $Document -Name 'value' -Attributes @{ type = $component.ValueType }
                $value.InnerText = $Field.logicalName
                [void]$parameters.AppendChild($value)
                [void]$customControl.AppendChild($parameters)
                [void]$description.AppendChild($customControl)
            }
            [void]$controlDescriptions.AppendChild($description)
}

function Add-FormFormatterSection {
    param(
        [xml]$Document,
        [Xml.XmlElement]$SectionsNode,
        $SectionPlan,
        [string]$IdentityBase,
        [hashtable]$ExistingCells
    )
    $visible = Get-FormFormatterBoolean (Get-FormFormatterProperty $SectionPlan 'visible' $true) $true
    $section = New-FormFormatterElement -Document $Document -Name 'section' -Attributes @{
        id = "{$((ConvertTo-FormFormatterStableGuid "$IdentityBase|section-id"))}"
        name = $SectionPlan.ownedName
        showlabel = 'true'
        visible = $visible.ToString().ToLowerInvariant()
        columns = "$($SectionPlan.columns)"
    }
    Add-FormFormatterLabel -Document $Document -Parent $section -Text $SectionPlan.label
    $rows = New-FormFormatterElement -Document $Document -Name 'rows'
    $columns = [Math]::Max(1, [int]$SectionPlan.columns)
    $fieldIndex = 0
    while ($fieldIndex -lt @($SectionPlan.fields).Count) {
        $rowNumber = [int]($fieldIndex / $columns)
        $row = New-FormFormatterElement -Document $Document -Name 'row' -Attributes @{
            id = "{$((ConvertTo-FormFormatterStableGuid "$IdentityBase|row|$rowNumber"))}"
        }
        for ($column = 1; $column -le $columns -and $fieldIndex -lt @($SectionPlan.fields).Count; $column++) {
            $field = @($SectionPlan.fields)[$fieldIndex]
            $cell = [Xml.XmlElement]$Document.ImportNode($ExistingCells[$field.logicalName.ToLowerInvariant()], $true)
            $cell.SetAttribute('id', "{$((ConvertTo-FormFormatterStableGuid "$IdentityBase|cell|$($field.logicalName)"))}")
            $cell.SetAttribute('showlabel', 'true')
            $cell.SetAttribute('colspan', '1')
            foreach ($labels in @($cell.SelectNodes('./labels'))) { [void]$cell.RemoveChild($labels) }
            $labels = New-FormFormatterElement -Document $Document -Name 'labels'
            [void]$labels.AppendChild((New-FormFormatterElement -Document $Document -Name 'label' -Attributes @{
                description = $field.label
                languagecode = '1033'
            }))
            [void]$cell.PrependChild($labels)
            Set-FormFormatterFieldComponent -Document $Document -Cell $cell -Field $field -IdentityBase "$IdentityBase|$($field.logicalName)"
            [void]$row.AppendChild($cell)
            $fieldIndex++
        }
        [void]$rows.AppendChild($row)
    }
    [void]$section.AppendChild($rows)
    [void]$SectionsNode.AppendChild($section)
}

function ConvertTo-FormFormatterXml {
    param([string]$ExistingFormXml, $Plan)
    [xml]$document = Assert-FormFormatterXml -FormXml $ExistingFormXml -FormName $Plan.formName
    $tabs = $document.SelectSingleNode('/form/tabs')
    if ($null -eq $tabs) {
        $tabs = New-FormFormatterElement -Document $document -Name 'tabs'
        [void]$document.DocumentElement.AppendChild($tabs)
    }

    $plannedFields = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    foreach ($tabPlan in @($Plan.tabs)) {
        foreach ($sectionPlan in @($tabPlan.sections)) {
            foreach ($field in @($sectionPlan.fields)) { [void]$plannedFields.Add($field.logicalName) }
        }
    }
    $existingCells = Get-FormFormatterPlannedCells -Document $document -PlannedFields $plannedFields

    $ownedPrefix = "$script:FormatterPrefix-$($Plan.scenarioSlug)-$($Plan.tableLogicalName)-"
    foreach ($tab in @($tabs.SelectNodes("./tab[starts-with(@name,'$ownedPrefix')]"))) {
        [void]$tabs.RemoveChild($tab)
    }
    Remove-FormFormatterPlannedCells -Document $document -PlannedFields $plannedFields

    foreach ($tabPlan in @($Plan.tabs)) {
        $identityBase = "$($Plan.scenarioSlug)|$($Plan.tableLogicalName)|$($Plan.formId)|$($tabPlan.key)"
        $tab = New-FormFormatterElement -Document $document -Name 'tab' -Attributes @{
            id = "{$((ConvertTo-FormFormatterStableGuid "$identityBase|tab-id"))}"
            name = $tabPlan.ownedName
            showlabel = 'true'
            expanded = (-not [bool]$tabPlan.collapsed).ToString().ToLowerInvariant()
        }
        Add-FormFormatterLabel -Document $document -Parent $tab -Text $tabPlan.label
        $columns = New-FormFormatterElement -Document $document -Name 'columns'
        $tabColumnNodes = @()
        for ($index = 0; $index -lt [int]$tabPlan.columns; $index++) {
            $column = New-FormFormatterElement -Document $document -Name 'column' -Attributes @{
                width = "$([Math]::Round(100 / [double]$tabPlan.columns, 2))%"
            }
            $sections = New-FormFormatterElement -Document $document -Name 'sections'
            [void]$column.AppendChild($sections)
            [void]$columns.AppendChild($column)
            $tabColumnNodes += $sections
        }
        $sectionIndex = 0
        foreach ($sectionPlan in @($tabPlan.sections)) {
            Add-FormFormatterSection -Document $document -SectionsNode $tabColumnNodes[$sectionIndex % $tabColumnNodes.Count] -SectionPlan $sectionPlan -IdentityBase "$identityBase|$($sectionPlan.key)" -ExistingCells $existingCells
            $sectionIndex++
        }
        [void]$tab.AppendChild($columns)
        [void]$tabs.AppendChild($tab)
    }
    return $document.OuterXml
}

function Get-FormFormatterSemanticState {
    param([string]$FormXml, [string]$OwnedPrefix)
    [xml]$document = Assert-FormFormatterXml -FormXml $FormXml -FormName 'semantic verification'
    $tabs = [Collections.Generic.List[object]]::new()
    foreach ($tab in @($document.SelectNodes("/form/tabs/tab[starts-with(@name,'$OwnedPrefix')]"))) {
        $sections = [Collections.Generic.List[object]]::new()
        foreach ($section in @($tab.SelectNodes('.//section'))) {
            $fields = @($section.SelectNodes('.//cell[control[@datafieldname]]') | ForEach-Object {
                $control = $_.SelectSingleNode('./control[@datafieldname]')
                $label = $_.SelectSingleNode('./labels/label')
                [pscustomobject][ordered]@{
                    logicalName = $control.GetAttribute('datafieldname')
                    label = if ($null -eq $label) { '' } else { $label.GetAttribute('description') }
                    colspan = $_.GetAttribute('colspan')
                    component = if ([string]::IsNullOrWhiteSpace($control.GetAttribute('uniqueid'))) {
                        ''
                    } else {
                        $description = $document.SelectSingleNode("/form/controlDescriptions/controlDescription[@forControl='$($control.GetAttribute('uniqueid'))']")
                        $namedControl = if ($null -eq $description) { $null } else { $description.SelectSingleNode('./customControl[@name]') }
                        $componentName = if ($null -eq $namedControl) { '' } else { $namedControl.GetAttribute('name') }
                        switch ($componentName) {
                            'MscrmControls.FieldControls.ToggleControl' { 'toggle' }
                            'MscrmControls.OptionSet.OptionSetControl' { 'option-set-wrapper' }
                            default { '' }
                        }
                    }
                }
            })
            $sectionLabel = $section.SelectSingleNode('./labels/label')
            $sections.Add([pscustomobject][ordered]@{
                name = $section.GetAttribute('name')
                label = if ($null -eq $sectionLabel) { '' } else { $sectionLabel.GetAttribute('description') }
                columns = $section.GetAttribute('columns')
                visible = $section.GetAttribute('visible')
                fields = @($fields)
            })
        }
        $tabLabel = $tab.SelectSingleNode('./labels/label')
        $tabs.Add([pscustomobject][ordered]@{
            name = $tab.GetAttribute('name')
            label = if ($null -eq $tabLabel) { '' } else { $tabLabel.GetAttribute('description') }
            expanded = $tab.GetAttribute('expanded')
            columns = $tab.SelectNodes('./columns/column').Count
            sections = @($sections.ToArray())
        })
    }
    return @($tabs.ToArray())
}

function New-FormFormatterNormalizedPlan {
    param(
        [string]$ScenarioSlug,
        $Layout,
        $Form,
        [object[]]$Attributes
    )
    $attributeMap = @{}
    foreach ($attribute in $Attributes) {
        $logicalName = "$(Get-FormFormatterProperty $attribute 'LogicalName')"
        if (-not [string]::IsNullOrWhiteSpace($logicalName)) { $attributeMap[$logicalName.ToLowerInvariant()] = $attribute }
    }
    $tabs = [Collections.Generic.List[object]]::new()
    foreach ($tab in @($Layout.tabs)) {
        $tabKey = "$($tab.key)"
        $tabColumns = [int](Get-FormFormatterProperty $tab 'columns' 0)
        if ($tabColumns -eq 0) {
            $tabColumns = switch ("$(Get-FormFormatterProperty $tab 'layout' 'one-column')") {
                'two-column' { 2 }
                'three-column' { 3 }
                default { 1 }
            }
        }
        $sections = [Collections.Generic.List[object]]::new()
        foreach ($section in @($tab.sections)) {
            $fields = [Collections.Generic.List[object]]::new()
            foreach ($fieldValue in @($section.fields)) {
                $field = Get-FormFormatterFieldSpec $fieldValue
                $key = $field.logicalName.ToLowerInvariant()
                if (-not $attributeMap.ContainsKey($key)) {
                    throw "Unknown field '$($field.logicalName)' on table '$($Layout.tableLogicalName)'."
                }
                $validForForm = Get-FormFormatterProperty $attributeMap[$key] 'IsValidForForm' $true
                if ($null -ne $validForForm -and -not [bool]$validForForm) {
                    throw "Field '$($field.logicalName)' is not valid for forms on table '$($Layout.tableLogicalName)'."
                }
                $attributeType = Get-FormFormatterAttributeType $attributeMap[$key]
                if ($field.component -eq 'toggle' -and $attributeType -cne 'Boolean') {
                    throw "Field '$($field.logicalName)' uses component 'toggle' but its Dataverse type is '$attributeType', not 'Boolean'."
                }
                if ($field.component -eq 'option-set-wrapper' -and $attributeType -cne 'Picklist') {
                    throw "Field '$($field.logicalName)' uses component 'option-set-wrapper' but its Dataverse type is '$attributeType', not 'Picklist'."
                }
                $fields.Add([pscustomobject][ordered]@{
                    logicalName = $field.logicalName
                    label = if ([string]::IsNullOrWhiteSpace($field.label)) { Get-FormFormatterAttributeLabel $attributeMap[$key] } else { $field.label }
                    component = $field.component
                })
            }
            $sections.Add([pscustomobject][ordered]@{
                key = "$($section.key)"
                ownedName = Get-FormFormatterOwnedName $ScenarioSlug $Layout.tableLogicalName 'section' "$($section.key)"
                label = "$($section.label)"
                columns = [int]$section.columns
                visible = Get-FormFormatterBoolean (Get-FormFormatterProperty $section 'visible' $true) $true
                fields = @($fields.ToArray())
            })
        }
        $tabs.Add([pscustomobject][ordered]@{
            key = $tabKey
            ownedName = Get-FormFormatterOwnedName $ScenarioSlug $Layout.tableLogicalName 'tab' $tabKey
            label = "$($tab.label)"
            columns = $tabColumns
            collapsed = Get-FormFormatterBoolean (Get-FormFormatterProperty $tab 'collapsed' $false) $false
            sections = @($sections.ToArray())
        })
    }
    return [pscustomobject][ordered]@{
        scenarioSlug = $ScenarioSlug
        tableLogicalName = "$($Layout.tableLogicalName)"
        formName = "$($Form.name)"
        formId = "$(Get-FormFormatterProperty $Form 'formid')".Trim('{}').ToLowerInvariant()
        ownershipMarker = "$script:Step60Marker; scenario=$ScenarioSlug"
        tabs = @($tabs.ToArray())
    }
}

function Write-FormFormatterArtifacts {
    param(
        [string]$ArtifactFolder,
        $PlanDocument,
        [object[]]$Results,
        [string]$Mode
    )
    New-Item -ItemType Directory -Path $ArtifactFolder -Force | Out-Null
    $PlanDocument | ConvertTo-Json -Depth 50 | Set-Content -LiteralPath (Join-Path $ArtifactFolder 'form-formatting-plan.json') -Encoding UTF8

    $diff = [Collections.Generic.List[string]]::new()
    $diff.Add('# Dataverse form formatting semantic diff') | Out-Null
    $diff.Add('') | Out-Null
    $diff.Add("- Scenario: $($PlanDocument.scenarioSlug)") | Out-Null
    $diff.Add("- Approved plan hash: ``$($PlanDocument.planHash)``") | Out-Null
    foreach ($result in $Results) {
        $diff.Add('') | Out-Null
        $diff.Add("## $($result.tableLogicalName) — $($result.formName)") | Out-Null
        $diff.Add("- Action: **$($result.action)**") | Out-Null
        $diff.Add("- Added/replaced: $($result.tabCount) formatter-owned tab(s), $($result.sectionCount) section(s).") | Out-Null
        $diff.Add("- Moved: $($result.fieldCount) planned field(s) into approved sections.") | Out-Null
        $diff.Add("- Components: $($result.componentCount) explicit Toggle or OptionSet Wrapper assignment(s), type-checked for all form factors.") | Out-Null
        $diff.Add("- Preserved: unlisted controls, unknown tabs/sections, libraries, handlers, header, and footer.") | Out-Null
        $diff.Add("- Removed: prior formatter-owned structures only; no unknown structure is replaced.") | Out-Null
    }
    $diff | Set-Content -LiteralPath (Join-Path $ArtifactFolder 'form-formatting-diff.md') -Encoding UTF8

    $html = [Text.StringBuilder]::new()
    [void]$html.Append("<!doctype html><html lang='en'><head><meta charset='utf-8'><meta name='viewport' content='width=device-width'><title>Form layout preview</title><style>body{font:16px system-ui;margin:0;background:#f5f7fa;color:#172b4d}main{max-width:1100px;margin:auto;padding:2rem}.notice{border-left:5px solid #0067b8;background:white;padding:1rem}.form{background:white;margin:1.5rem 0;padding:1.25rem;border-radius:.5rem}.tabs{display:grid;gap:1rem}.tab{border:1px solid #b8c4ce;padding:1rem}.sections{display:grid;grid-template-columns:repeat(auto-fit,minmax(240px,1fr));gap:1rem}.section{background:#f7f9fb;padding:1rem}.fields{display:grid;gap:.6rem}.field{border:1px solid #ccd6dd;background:white;padding:.65rem}h1,h2,h3,h4{line-height:1.2}</style></head><body><main><h1>Dataverse form layout preview</h1><p class='notice' role='note'><strong>Approximation:</strong> This accessible wireframe is not a live Power Apps render.</p>")
    foreach ($form in @($PlanDocument.forms)) {
        [void]$html.Append("<article class='form'><h2>$(ConvertTo-FormFormatterHtml $form.formName)</h2><p>Table: <code>$(ConvertTo-FormFormatterHtml $form.tableLogicalName)</code></p><div class='tabs'>")
        foreach ($tab in @($form.tabs)) {
            [void]$html.Append("<section class='tab'><h3>$(ConvertTo-FormFormatterHtml $tab.label)</h3><div class='sections'>")
            foreach ($section in @($tab.sections)) {
                [void]$html.Append("<section class='section'><h4>$(ConvertTo-FormFormatterHtml $section.label)</h4><div class='fields' style='grid-template-columns:repeat($($section.columns),minmax(0,1fr))'>")
                foreach ($field in @($section.fields)) {
                    $component = if ([string]::IsNullOrWhiteSpace("$($field.component)")) { '' } else { "<br><small>Component: $(ConvertTo-FormFormatterHtml $field.component)</small>" }
                    [void]$html.Append("<div class='field'><strong>$(ConvertTo-FormFormatterHtml $field.label)</strong><br><code>$(ConvertTo-FormFormatterHtml $field.logicalName)</code>$component</div>")
                }
                [void]$html.Append('</div></section>')
            }
            [void]$html.Append('</div></section>')
        }
        [void]$html.Append('</div></article>')
    }
    [void]$html.Append('</main></body></html>')
    $html.ToString() | Set-Content -LiteralPath (Join-Path $ArtifactFolder 'form-formatting-preview.html') -Encoding UTF8

    [pscustomobject][ordered]@{
        scenarioSlug = $PlanDocument.scenarioSlug
        mode = $Mode
        planHash = $PlanDocument.planHash
        forms = @($Results)
    } | ConvertTo-Json -Depth 30 | Set-Content -LiteralPath (Join-Path $ArtifactFolder 'form-formatting-report.json') -Encoding UTF8
}

function Invoke-WizardFormFormatting {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)] [string]$RepoRoot,
        [Parameter(Mandatory)] [string]$ScenarioSlug,
        [ValidateSet('Preview', 'Apply')] [string]$Mode = 'Preview',
        [string]$ApprovedPlanHash = '',
        [string]$EnvironmentUrl,
        [string]$AccessToken,
        [string]$SolutionUniqueName,
        [string]$PublisherPrefix,
        [scriptblock]$RequestInvoker
    )

    $layoutPath = Join-Path $RepoRoot "specs\$ScenarioSlug\form-layouts.json"
    $schemaPath = Join-Path $RepoRoot 'schemas\payloads\form-layouts.schema.json'
    if (-not (Test-Path -LiteralPath $layoutPath -PathType Leaf)) { throw "Form layout contract not found: $layoutPath" }
    if (-not (Test-Path -LiteralPath $schemaPath -PathType Leaf)) { throw "Form layout schema not found: $schemaPath" }
    $layoutJson = Get-Content -LiteralPath $layoutPath -Raw -Encoding UTF8
    if (-not (Test-Json -Json $layoutJson -SchemaFile $schemaPath -ErrorAction Stop)) { throw 'form-layouts.json failed schema validation.' }
    $payload = $layoutJson | ConvertFrom-Json
    Assert-FormFormatterContract $payload

    if ([string]::IsNullOrWhiteSpace($EnvironmentUrl)) { $EnvironmentUrl = 'https://formatter.invalid' }
    if ([string]::IsNullOrWhiteSpace($AccessToken)) { $AccessToken = 'injected-request-token' }
    if ($null -eq $RequestInvoker -and ($EnvironmentUrl -eq 'https://formatter.invalid' -or $AccessToken -eq 'injected-request-token')) {
        throw 'Dataverse credentials are required unless RequestInvoker is supplied.'
    }
    if ($Mode -eq 'Apply') {
        if ([string]::IsNullOrWhiteSpace($ApprovedPlanHash)) { throw 'Apply requires -ApprovedPlanHash from Preview.' }
        foreach ($value in @($SolutionUniqueName, $PublisherPrefix)) {
            if ([string]::IsNullOrWhiteSpace($value)) { throw 'Apply requires solution and publisher identity for the artifact manifest.' }
        }
    }

    $invoke = {
        param([string]$Method, [string]$Path, $Body = $null)
        Invoke-WizardDataverseRequest -Method $Method -Path $Path -EnvironmentUrl $EnvironmentUrl -AccessToken $AccessToken -Body $Body -RequestInvoker $RequestInvoker
    }
    $resolvedPlans = [Collections.Generic.List[object]]::new()
    $runtime = [Collections.Generic.List[object]]::new()
    $resolvedFormIds = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    foreach ($layout in @($payload.forms)) {
        $safeTable = ConvertTo-WizardODataLiteral "$($layout.tableLogicalName)"
        $table = & $invoke Get "EntityDefinitions(LogicalName='$safeTable')?`$select=LogicalName,IsCustomEntity"
        if ($null -eq $table -or "$(Get-FormFormatterProperty $table 'LogicalName')" -cne "$($layout.tableLogicalName)") {
            throw "Table '$($layout.tableLogicalName)' was not resolved."
        }
        if (-not [bool](Get-FormFormatterProperty $table 'IsCustomEntity' $false)) {
            throw "Table '$($layout.tableLogicalName)' is not custom. Version 1 formats wizard-owned custom forms only."
        }
        $attributes = @((& $invoke Get "EntityDefinitions(LogicalName='$safeTable')/Attributes?`$select=LogicalName,DisplayName,IsValidForForm").value)
        $forms = @((& $invoke Get "systemforms?`$select=formid,name,type,formxml,description,ismanaged,iscustomizable,formactivationstate&`$filter=objecttypecode eq '$safeTable' and type eq 2").value)
        $form = Get-FormFormatterFormMatch -Layout $layout -Forms $forms
        if ("$(Get-FormFormatterProperty $form 'name')" -cne "$($layout.formName)") {
            throw "Form ID '$($layout.formId)' resolved to '$($form.name)', not declared form '$($layout.formName)'."
        }
        $resolvedFormKey = "$($layout.tableLogicalName)|$("$(Get-FormFormatterProperty $form 'formid')".Trim('{}'))"
        if (-not $resolvedFormIds.Add($resolvedFormKey)) {
            throw "Multiple form layouts resolve to the same form '$resolvedFormKey'."
        }
        if ([int](Get-FormFormatterProperty $form 'type' 2) -ne 2) { throw "Form '$($layout.formName)' is not a Main form." }
        if ([bool](Get-FormFormatterProperty $form 'ismanaged' $false)) { throw "Form '$($layout.formName)' is managed/noncustom and cannot be formatted." }
        if ([int](Get-FormFormatterProperty $form 'formactivationstate' 1) -ne 1) { throw "Form '$($layout.formName)' is inactive and cannot be formatted." }
        $isCustomizable = Get-FormFormatterProperty $form 'iscustomizable'
        if ($null -ne $isCustomizable) {
            $customizableValue = if ($isCustomizable -is [bool]) { $isCustomizable } else { Get-FormFormatterProperty $isCustomizable 'Value' $false }
            if (-not [bool]$customizableValue) { throw "Form '$($layout.formName)' is noncustomizable and cannot be formatted." }
        }
        if ("$(Get-FormFormatterProperty $form 'description')" -cne "$script:Step60Marker; scenario=$ScenarioSlug") {
            throw "Form '$($layout.formName)' does not carry the exact step 60 ownership marker for scenario '$ScenarioSlug'."
        }
        [xml]$null = Assert-FormFormatterXml -FormXml "$(Get-FormFormatterProperty $form 'formxml')" -FormName "$($layout.formName)"
        $plan = New-FormFormatterNormalizedPlan -ScenarioSlug $ScenarioSlug -Layout $layout -Form $form -Attributes $attributes
        $desiredXml = ConvertTo-FormFormatterXml -ExistingFormXml "$($form.formxml)" -Plan $plan
        [xml]$null = Assert-FormFormatterXml -FormXml $desiredXml -FormName "$($layout.formName) desired"
        $changed = "$($form.formxml)" -cne $desiredXml
        $resolvedPlans.Add($plan)
        $runtime.Add([pscustomobject]@{ layout = $layout; form = $form; plan = $plan; desiredXml = $desiredXml; changed = $changed })
    }

    $planCore = [pscustomobject][ordered]@{
        version = '1.0'
        scenarioSlug = $ScenarioSlug
        forms = @($resolvedPlans.ToArray())
    }
    $canonicalPlan = $planCore | ConvertTo-Json -Depth 50 -Compress
    $planHash = Get-FormFormatterHash $canonicalPlan
    $planDocument = [pscustomobject][ordered]@{
        version = '1.0'
        scenarioSlug = $ScenarioSlug
        planHash = $planHash
        forms = @($resolvedPlans.ToArray())
    }
    if ($Mode -eq 'Apply' -and $ApprovedPlanHash -cne $planHash) {
        throw "ApprovedPlanHash mismatch. Expected '$planHash'; received '$ApprovedPlanHash'. Run Preview again."
    }

    $artifactFolder = Join-Path $RepoRoot ".wizard-metrics\artifacts\form-formatting\$ScenarioSlug"
    $results = [Collections.Generic.List[object]]::new()
    $changedTables = [Collections.Generic.List[string]]::new()
    foreach ($item in @($runtime.ToArray())) {
        $formId = "$($item.plan.formId)"
        $action = if ($item.changed) { if ($Mode -eq 'Apply') { 'updated' } else { 'update-planned' } } else { 'unchanged' }
        if ($Mode -eq 'Apply' -and $item.changed) {
            $snapshotFolder = Join-Path $artifactFolder 'form-formatting-before'
            New-Item -ItemType Directory -Path $snapshotFolder -Force | Out-Null
            "$($item.form.formxml)" | Set-Content -LiteralPath (Join-Path $snapshotFolder "$formId.formxml.xml") -Encoding UTF8
            & $invoke Patch "systemforms($formId)" @{ formxml = $item.desiredXml } | Out-Null
            $changedTables.Add("$($item.plan.tableLogicalName)")
        }
        $result = [pscustomobject][ordered]@{
            tableLogicalName = $item.plan.tableLogicalName
            formName = $item.plan.formName
            formId = $formId
            action = $action
            tabCount = @($item.plan.tabs).Count
            sectionCount = @($item.plan.tabs | ForEach-Object { @($_.sections).Count | Measure-Object -Sum } | ForEach-Object Sum | Measure-Object -Sum).Sum
            fieldCount = @($item.plan.tabs | ForEach-Object { $_.sections } | ForEach-Object { $_.fields }).Count
            componentCount = @($item.plan.tabs | ForEach-Object { $_.sections } | ForEach-Object { $_.fields } | Where-Object { -not [string]::IsNullOrWhiteSpace("$($_.component)") }).Count
            verified = $Mode -eq 'Preview'
        }
        $results.Add($result)
    }

    if ($Mode -eq 'Apply' -and $changedTables.Count -gt 0) {
        $publishXml = New-WizardEntityPublishXml -EntityLogicalNames @($changedTables.ToArray())
        & $invoke Post 'PublishXml' @{ ParameterXml = $publishXml } | Out-Null
    }

    if ($Mode -eq 'Apply') {
        foreach ($index in 0..($runtime.Count - 1)) {
            $item = $runtime[$index]
            $formId = "$($item.plan.formId)"
            $readback = & $invoke Get "systemforms($formId)?`$select=formid,name,type,formxml,description,ismanaged"
            if ($null -eq $readback -or "$(Get-FormFormatterProperty $readback 'description')" -cne "$script:Step60Marker; scenario=$ScenarioSlug") {
                throw "Readback verification failed for form '$($item.plan.formName)'."
            }
            $ownedPrefix = "$script:FormatterPrefix-$ScenarioSlug-$($item.plan.tableLogicalName)-"
            $expectedState = Get-FormFormatterSemanticState -FormXml $item.desiredXml -OwnedPrefix $ownedPrefix
            $actualState = Get-FormFormatterSemanticState -FormXml "$(Get-FormFormatterProperty $readback 'formxml')" -OwnedPrefix $ownedPrefix
            if (($expectedState | ConvertTo-Json -Depth 30 -Compress) -cne ($actualState | ConvertTo-Json -Depth 30 -Compress)) {
                throw "Readback semantic verification failed for form '$($item.plan.formName)'."
            }
            $results[$index].verified = $true
            Add-WizardArtifactManifestItem -RepoRoot $RepoRoot -ScenarioSlug $ScenarioSlug -SolutionName $SolutionUniqueName -PublisherPrefix $PublisherPrefix -Kind 'form-formatting' -Name "$($item.plan.tableLogicalName)|$formId" -Status $results[$index].action -Step '63-format-forms.ps1' -Details @{
                formId = $formId
                formName = $item.plan.formName
                planHash = $planHash
                verified = $true
            } | Out-Null
        }
    }

    Write-FormFormatterArtifacts -ArtifactFolder $artifactFolder -PlanDocument $planDocument -Results @($results.ToArray()) -Mode $Mode
    return [pscustomobject]@{
        PlanHash = $planHash
        ArtifactFolder = $artifactFolder
        Results = @($results.ToArray())
        ChangedCount = @($results | Where-Object { $_.action -in @('updated', 'update-planned') }).Count
    }
}

if ($env:WIZARD_FORM_FORMATTING_SKIP_MAIN -ne 'true') {
    $result = Invoke-WizardFormFormatting -RepoRoot $repoRoot -ScenarioSlug $ScenarioSlug -Mode $Mode -ApprovedPlanHash $ApprovedPlanHash -EnvironmentUrl $EnvironmentUrl -AccessToken $AccessToken -SolutionUniqueName $SolutionUniqueName -PublisherPrefix $PublisherPrefix -RequestInvoker $RequestInvoker
    Write-Host "Form formatting $Mode complete. Plan hash: $($result.PlanHash); changed: $($result.ChangedCount)" -ForegroundColor Green
    Write-Host "Artifacts: $($result.ArtifactFolder)" -ForegroundColor Gray
}
