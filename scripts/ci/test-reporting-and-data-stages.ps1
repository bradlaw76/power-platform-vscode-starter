Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
$payloads = Join-Path $repoRoot 'payloads/scenarios/gcc-framework-acceptance'
$testRepoRoot = Join-Path ([IO.Path]::GetTempPath()) "wizard-report-data-$([guid]::NewGuid())"
New-Item -ItemType Directory -Path $testRepoRoot -Force | Out-Null
$env:WIZARD_REPORTING_SKIP_MAIN = 'true'
$env:WIZARD_DATA_SKIP_MAIN = 'true'
. (Join-Path $repoRoot 'scripts/bootstrap/64-build-charts-dashboard.ps1') -ScenarioSlug 'ignored' -TargetProjectRoot $testRepoRoot
. (Join-Path $repoRoot 'scripts/bootstrap/66-seed-synthetic-data.ps1') -ScenarioSlug 'ignored'
Remove-Item Env:WIZARD_REPORTING_SKIP_MAIN, Env:WIZARD_DATA_SKIP_MAIN

$transportCalls = [Collections.Generic.List[object]]::new()
$charts = [Collections.Generic.List[object]]::new()
$dashboardState = [Collections.Generic.List[object]]::new()
$reportInvoker = {
    param($request)
    $path = ($request.Uri -split '/api/data/v9.2/')[1]
    $body = if ($request.Body) { $request.Body | ConvertFrom-Json } else { $null }
    $transportCalls.Add([pscustomobject]@{ Method=$request.Method; Path=$path; Body=$body })
    if ($path -like 'solutions?*') { return [pscustomobject]@{ value=@([pscustomobject]@{ solutionid='solution-id' }) } }
    if ($path -like 'solutioncomponents?*') { return [pscustomobject]@{ value=@([pscustomobject]@{ solutioncomponentid='membership-id' }) } }
    if ($path -like 'savedqueries?*') {
        $table = [uri]::UnescapeDataString($path) -replace ".*returnedtypecode eq '([^']+)'.*", '$1'
        return [pscustomobject]@{ value=@(
            [pscustomobject]@{ savedqueryid="view-$table"; returnedtypecode=$table; querytype=0; description="Generated by 60-build-forms-views.ps1; scenario=gcc-framework-acceptance" },
            [pscustomobject]@{ savedqueryid="foia-view-$table"; returnedtypecode=$table; querytype=0; description="Generated by 60-build-forms-views.ps1; scenario=federal-foia-management" }
        ) }
    }
    if ($path -like 'savedqueryvisualizations?*') {
        $name = [uri]::UnescapeDataString($path) -replace ".*name eq '([^']+)'.*", '$1'
        return [pscustomobject]@{ value=@($charts | Where-Object name -eq $name) }
    }
    if ($path -like 'systemforms?*') {
        $name = [uri]::UnescapeDataString($path) -replace ".*name eq '([^']+)'.*", '$1'
        return [pscustomobject]@{ value=@($dashboardState | Where-Object name -eq $name) }
    }
    if ($request.Method -eq 'Get' -and $path -match '^systemforms\(([^)]+)\)\?') {
        return @($dashboardState | Where-Object formid -eq $Matches[1])[0]
    }
    if ($request.Method -eq 'Post' -and $path -eq 'savedqueryvisualizations') {
        $item = [pscustomobject]@{ savedqueryvisualizationid="chart-$($charts.Count + 1)"; name=$body.name; primaryentitytypecode=$body.primaryentitytypecode; description=$body.description; datadescription=$body.datadescription; presentationdescription=$body.presentationdescription }
        $charts.Add($item); return $item
    }
    if ($request.Method -eq 'Patch' -and $path -match '^savedqueryvisualizations\(([^)]+)\)$') {
        $item = @($charts | Where-Object savedqueryvisualizationid -eq $Matches[1])[0]
        $item.datadescription = $body.datadescription
        $item.presentationdescription = $body.presentationdescription
        return [pscustomobject]@{}
    }
    if ($request.Method -eq 'Post' -and $path -eq 'systemforms') {
        $item = [pscustomobject]@{ formid="dashboard-$($dashboardState.Count + 1)"; name=$body.name; type=0; description=$body.description; formxml=$body.formxml }
        $dashboardState.Add($item); return $item
    }
    if ($request.Method -eq 'Patch' -and $path -match '^systemforms\(([^)]+)\)$') {
        $item = @($dashboardState | Where-Object formid -eq $Matches[1])[0]
        if ($body.PSObject.Properties.Name -contains 'formxml') { $item.formxml = $body.formxml }
        if ($body.PSObject.Properties.Name -contains 'formactivationstate') {
            if (-not ($item.PSObject.Properties.Name -contains 'formactivationstate')) { $item | Add-Member -NotePropertyName formactivationstate -NotePropertyValue $body.formactivationstate }
            else { $item.formactivationstate = $body.formactivationstate }
        }
        return [pscustomobject]@{}
    }
    return [pscustomobject]@{}
}

$firstReports = @(Invoke-WizardReportingStage -RepoRoot $testRepoRoot -ScenarioSlug 'gcc-framework-acceptance' -PayloadsFolder $payloads -EnvironmentUrl 'https://unit.test' -AccessToken 'token' -SolutionUniqueName 'UnitSolution' -PublisherPrefix 'ppvs' -RequestInvoker $reportInvoker)
$firstReportIds = @($firstReports.id)
$nativeChart = $charts[0]
[xml]$nativeData = $nativeChart.datadescription
[xml]$nativePresentation = $nativeChart.presentationdescription
if ($nativeData.SelectSingleNode('//category[not(@alias)]/measurecollection/measure[@alias="aggregate_column"]') -eq $null) {
    throw 'Generated native chart data description must use an unaliased category with the Dataverse aggregate_column contract.'
}
if ($nativeData.SelectSingleNode('//fetch[@aggregate="true"]/entity/attribute[@groupby="true" and @alias="groupby_column"]') -eq $null -or
    $nativeData.SelectSingleNode('//fetch[@aggregate="true"]/entity/attribute[@alias="aggregate_column"]') -eq $null) {
    throw 'Generated native chart data description must bind the groupby and aggregate aliases to FetchXML.'
}
$series = $nativePresentation.SelectSingleNode('//Series/Series')
if ($series -eq $null -or $series.HasAttribute('YValueMembers')) {
    throw 'Generated native chart presentation must use the Dataverse-inferred series binding contract.'
}
if ($nativePresentation.SelectSingleNode('//ChartAreas/ChartArea/AxisY/MajorGrid') -eq $null) {
    throw 'Generated native chart presentation must include the complete native chart-area contract.'
}
if ($nativePresentation.SelectSingleNode('//Series/Series/SmartLabelStyle[@Enabled="True"]') -eq $null) {
    throw 'Generated native chart presentation must include the native smart-label contract.'
}
$firstDashboardControls = @(Get-WizardDashboardControlSignatures -FormXml $dashboardState[0].formxml)
if ($firstDashboardControls.Count -eq 0 -or @($firstDashboardControls | Where-Object { $_ -notmatch '\|view-[^|]+\|[^|]+\|chart$' }).Count -gt 0) {
    throw 'Generated dashboard controls must include visualization, view, target table, and Chart mode.'
}
$secondReports = @(Invoke-WizardReportingStage -RepoRoot $testRepoRoot -ScenarioSlug 'gcc-framework-acceptance' -PayloadsFolder $payloads -EnvironmentUrl 'https://unit.test' -AccessToken 'token' -SolutionUniqueName 'UnitSolution' -PublisherPrefix 'ppvs' -RequestInvoker $reportInvoker)
if ($charts.Count -ne 2 -or $dashboardState.Count -ne 1) { throw 'Reporting rerun created duplicates.' }
if (Compare-Object $firstReportIds @($secondReports.id)) { throw 'Reporting IDs changed on rerun.' }
if (@($transportCalls | Where-Object { $_.Method -eq 'Post' -and $_.Path -in @('savedqueryvisualizations','systemforms') }).Count -ne 3) { throw 'Reporting rerun issued duplicate create requests.' }
if (@($secondReports | Where-Object action -ne 'skipped').Count -ne 0) { throw 'Reporting rerun should skip unchanged charts and dashboards.' }
$beforePreview = $transportCalls.Count
Invoke-WizardReportingStage -RepoRoot $testRepoRoot -ScenarioSlug 'gcc-framework-acceptance' -PayloadsFolder $payloads -PreviewOnly | Out-Null
if ($transportCalls.Count -ne $beforePreview) { throw 'Reporting preview invoked transport.' }

$foiaPayloads = Join-Path $repoRoot 'payloads/scenarios/federal-foia-management'
$foiaPreview = @(Invoke-WizardReportingStage -RepoRoot $testRepoRoot -ScenarioSlug 'federal-foia-management' -PayloadsFolder $foiaPayloads -PreviewOnly)
if (@($foiaPreview | Where-Object kind -eq 'dashboard').Count -ne 5) { throw 'FOIA reporting preview must plan five dashboards.' }
if ($transportCalls.Count -ne $beforePreview) { throw 'Multi-dashboard preview invoked transport.' }
$firstFoia = @(Invoke-WizardReportingStage -RepoRoot $testRepoRoot -ScenarioSlug 'federal-foia-management' -PayloadsFolder $foiaPayloads -EnvironmentUrl 'https://unit.test' -AccessToken 'token' -SolutionUniqueName 'UnitSolution' -PublisherPrefix 'foia' -RequestInvoker $reportInvoker)
$firstFoiaIds = @($firstFoia | Where-Object kind -eq 'dashboard' | ForEach-Object id)
$secondFoia = @(Invoke-WizardReportingStage -RepoRoot $testRepoRoot -ScenarioSlug 'federal-foia-management' -PayloadsFolder $foiaPayloads -EnvironmentUrl 'https://unit.test' -AccessToken 'token' -SolutionUniqueName 'UnitSolution' -PublisherPrefix 'foia' -RequestInvoker $reportInvoker)
if ($dashboardState.Count -ne 6) { throw 'Multi-dashboard apply did not create exactly five additional dashboards.' }
if (Compare-Object $firstFoiaIds @($secondFoia | Where-Object kind -eq 'dashboard' | ForEach-Object id)) { throw 'Multi-dashboard IDs changed on rerun.' }
if (@($transportCalls | Where-Object { $_.Method -eq 'Post' -and $_.Path -eq 'systemforms' }).Count -ne 6) { throw 'Multi-dashboard rerun created duplicate dashboards.' }
if (@($secondFoia | Where-Object action -ne 'skipped').Count -ne 0) { throw 'FOIA reporting rerun should skip unchanged charts and dashboards.' }
$charts.Add([pscustomobject]@{ savedqueryvisualizationid='collision'; name=$charts[0].name; primaryentitytypecode=$charts[0].primaryentitytypecode; description=$charts[0].description })
try { Invoke-WizardReportingStage -RepoRoot $testRepoRoot -ScenarioSlug 'gcc-framework-acceptance' -PayloadsFolder $payloads -EnvironmentUrl 'https://unit.test' -AccessToken 'token' -SolutionUniqueName 'UnitSolution' -PublisherPrefix 'ppvs' -RequestInvoker $reportInvoker | Out-Null; throw 'Expected reporting collision failure.' } catch { if ($_.Exception.Message -notmatch 'collision') { throw } }

$records = @{}
$dataCreates = 0
$dataInvoker = {
    param($request)
    $path = [uri]::UnescapeDataString(($request.Uri -split '/api/data/v9.2/')[1])
    $body = if ($request.Body) { $request.Body | ConvertFrom-Json } else { $null }
    if ($path -like 'solutions?*') { return [pscustomobject]@{ value=@([pscustomobject]@{ solutionid='solution-id' }) } }
    if ($path -match "EntityDefinitions\(LogicalName='([^']+)'\)") {
        $logicalName=$Matches[1]; return [pscustomobject]@{ LogicalName=$logicalName; EntitySetName="${logicalName}s"; PrimaryIdAttribute="${logicalName}id" }
    }
    if ($request.Method -eq 'Get' -and $path -match '^([^?]+)\?.*\$filter=([^ ]+) eq ''([^'']+)''') {
        $set=$Matches[1]; $value=$Matches[3]; $matches=@($records.Values | Where-Object { $_.set -eq $set -and $_.key -eq $value }); return [pscustomobject]@{ value=$matches }
    }
    if ($request.Method -eq 'Post') {
        $set=$path; $keyProperty=@($body.PSObject.Properties | Where-Object Name -in @('ppvs_assettag','ppvs_requestnumber'))[0]; $idProperty=$set.TrimEnd('s')+'id'; $id="record-$($records.Count + 1)"
        $item=[pscustomobject]@{ set=$set; key="$($keyProperty.Value)"; ppvs_acceptancesourcetag=$body.ppvs_acceptancesourcetag }; $item | Add-Member -NotePropertyName $idProperty -NotePropertyValue $id
        $records["$set|$($keyProperty.Value)"]=$item; $script:dataCreates++; return $item
    }
    return [pscustomobject]@{}
}
$firstData = @(Invoke-WizardSyntheticDataStage -RepoRoot $testRepoRoot -ScenarioSlug 'gcc-framework-acceptance' -PayloadsFolder $payloads -EnvironmentUrl 'https://unit.test' -AccessToken 'token' -SolutionUniqueName 'UnitSolution' -RequestInvoker $dataInvoker)
$firstDataIds = @($firstData.id)
$secondData = @(Invoke-WizardSyntheticDataStage -RepoRoot $testRepoRoot -ScenarioSlug 'gcc-framework-acceptance' -PayloadsFolder $payloads -EnvironmentUrl 'https://unit.test' -AccessToken 'token' -SolutionUniqueName 'UnitSolution' -RequestInvoker $dataInvoker)
if ($records.Count -ne 8 -or $dataCreates -ne 8) { throw 'Synthetic-data rerun created duplicates.' }
if (Compare-Object $firstDataIds @($secondData.id)) { throw 'Synthetic-data IDs changed on rerun.' }
$beforeDataPreview=$dataCreates
Invoke-WizardSyntheticDataStage -RepoRoot $testRepoRoot -ScenarioSlug 'gcc-framework-acceptance' -PayloadsFolder $payloads -PreviewOnly | Out-Null
if ($dataCreates -ne $beforeDataPreview) { throw 'Synthetic-data preview invoked transport.' }

Write-Host 'Reporting and synthetic-data stage tests passed.' -ForegroundColor Green
Remove-Item -LiteralPath $testRepoRoot -Recurse -Force -ErrorAction SilentlyContinue